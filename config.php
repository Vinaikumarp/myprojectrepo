The phrase "config php" usually refers to one of two things: configuring the global PHP environment using the php.
ini file, or creating a custom config.php file for a web application to store settings like database credentials.
1. Global Environment Configuration (php.ini)The php.ini core configuration file controls PHP's behavior, memory limits, and file upload rules.
Locate the file: Run php --ini in your terminal to see exactly where your php.ini file resides.
